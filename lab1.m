clc;
clear;
close all;

%% 1. Загрузка изображения
f = imread('my_image.jpg');

% Если изображение цветное, переводим его в оттенки серого
if ndims(f) == 3
    f = rgb2gray(f);
end

% Размер изображения
[M, N] = size(f);

disp('Размер изображения:');
fprintf('Строк: %d\n', M);
fprintf('Столбцов: %d\n', N);

% Дополнительная информация о массиве
whos f


%% 2. Вывод исходного изображения и сохранение
figure;
imshow(f, []);
title('Исходное изображение');

imwrite(f, 'saved_image.png');


%% 3. Отражение относительно горизонтальной оси
f_flip = f(end:-1:1, :);

figure;
imshow(f_flip, []);
title('Отражение относительно горизонтальной оси');


%% 4. Уменьшение изображения прореживанием

% В 2 раза
f2 = f(1:2:end, 1:2:end);

figure;
imshow(f2, []);
title('Изображение, уменьшенное в 2 раза');

% В 4 раза
f4 = f(1:4:end, 1:4:end);

figure;
imshow(f4, []);
title('Изображение, уменьшенное в 4 раза');


%% 5. Обрезка изображения до квадратного
n = min(M, N);

f_square = f(1:n, 1:n);

figure;
imshow(f_square, []);
title('Квадратное изображение');


%% 6. Создание квадратной матрицы такого же размера
B = rand(n);

figure;
imshow(B, []);
title('Матрица rand(n)');


%% 7. Перемножение матриц
A = double(f_square);

C = A * B;

figure;
imshow(C, []);
title('Результат умножения матриц');
